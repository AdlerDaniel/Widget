function quoteForDate(dateKey) {
  if (typeof dateKey !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(dateKey))
    throw new TypeError("dateKey должен иметь формат YYYY-MM-DD");
  const timestamp = Date.parse(dateKey + "T00:00:00Z");
  if (
    !Number.isFinite(timestamp) ||
    new Date(timestamp).toISOString().slice(0, 10) !== dateKey
  )
    throw new RangeError("dateKey содержит неверную дату");
  const dayNumber = Math.floor(timestamp / 86400000);
  const index = ((dayNumber % QUOTES.length) + QUOTES.length) % QUOTES.length;
  return QUOTES[index];
}

